def check(name, ok, detail=""):
    result["assertions"].append({"name": name, "ok": bool(ok), "detail": str(detail)})
    print(("PASS" if ok else "FAIL"), name, f"({detail})" if detail else "")


def shot(page, name):
    path = OUT / name
